import { beforeEach, describe, expect, it } from "vitest";

import { renderDraftEmail, sanitizeRun } from "./draft-email";
import { checkRateLimit, resetRateLimits } from "./rate-limit";

function validRun(overrides: Record<string, unknown> = {}) {
  return {
    fit: "good",
    source: "heuristic",
    scope: {
      problem: "Leads fall through a spreadsheet",
      deliverables: ["Score inbound leads", "Weekly Slack digest"],
      constraints: [],
      budgetSignal: { amountMinor: 600_000, currency: "USD", confidence: "hinted", raw: "$6k" },
      deadline: { date: "2026-08-27", driver: "trade show", raw: "in three weeks" },
    },
    doc: {
      intro: "That's the thing this fixes.",
      scope: ["Score inbound leads"],
      pricing: {
        rows: [{ label: "Discovery & mapping", amountMinor: 60_000 }],
        totalMinor: 290_000,
        currency: "USD",
        note: null,
      },
      assumptions: ["You provide access."],
      terms: ["[50%] on acceptance."],
    },
    followUps: [
      { subject: "Re: leads", sendOffsetDays: 3, sendDateLabel: "Sun 9 Aug", body: "It's with you." },
    ],
    ...overrides,
  };
}

const META = { siteName: "[Autoworks]", origin: "https://example.vercel.app" };

describe("sanitizeRun", () => {
  it("accepts a well-formed run", () => {
    const safe = sanitizeRun(validRun());
    expect(safe).not.toBeNull();
    expect(safe!.deliverables).toHaveLength(2);
    expect(safe!.total).toContain("2,900");
    expect(safe!.budget).toBe("$6k (hinted)");
  });

  it("rejects junk instead of mailing it", () => {
    expect(sanitizeRun(null)).toBeNull();
    expect(sanitizeRun("hello")).toBeNull();
    expect(sanitizeRun({})).toBeNull();
    expect(sanitizeRun({ doc: {}, scope: {} })).toBeNull();
  });

  it("caps runaway field lengths", () => {
    const safe = sanitizeRun(
      validRun({
        doc: { ...validRun().doc, intro: "x".repeat(50_000) },
      }),
    );
    expect(safe!.intro.length).toBeLessThanOrEqual(900);
  });

  it("caps list lengths so a payload can't balloon the email", () => {
    const safe = sanitizeRun(
      validRun({
        scope: {
          ...validRun().scope,
          deliverables: Array.from({ length: 500 }, (_, i) => `item ${i}`),
        },
        followUps: Array.from({ length: 80 }, () => ({
          subject: "s",
          sendDateLabel: "Mon 1 Jan",
          body: "b",
        })),
      }),
    );
    expect(safe!.deliverables.length).toBeLessThanOrEqual(12);
    expect(safe!.followUps.length).toBeLessThanOrEqual(5);
  });

  it("falls back to a safe confidence rather than echoing arbitrary values", () => {
    const safe = sanitizeRun(
      validRun({
        scope: {
          ...validRun().scope,
          budgetSignal: { confidence: "<script>", raw: "x", amountMinor: 1, currency: "USD" },
        },
      }),
    );
    expect(safe!.budget).toBe("not discussed");
  });
});

describe("renderDraftEmail", () => {
  it("escapes injected markup in every interpolated field", () => {
    const safe = sanitizeRun(
      validRun({
        scope: {
          ...validRun().scope,
          deliverables: ['<img src=x onerror="alert(1)">'],
        },
        doc: {
          ...validRun().doc,
          intro: "<script>alert('xss')</script>",
        },
      }),
    )!;

    const { html } = renderDraftEmail(safe, META);

    // What matters is that no tag or attribute delimiter survives — the words
    // "script" and "onerror" appearing as inert text is fine and expected.
    expect(html).not.toContain("<script");
    expect(html).not.toContain("<img");
    expect(html).toContain("&lt;script&gt;");
    expect(html).toContain("&lt;img");
    expect(html).toContain("onerror=&quot;");
  });

  it("uses a fixed subject the visitor cannot influence", () => {
    const safe = sanitizeRun(
      validRun({ doc: { ...validRun().doc, intro: "Subject: you have won" } }),
    )!;
    const { subject } = renderDraftEmail(safe, META);
    expect(subject).toBe("Your proposal draft from [Autoworks]");
  });

  it("says where the email came from, so it can't pass as a real quote", () => {
    const safe = sanitizeRun(validRun())!;
    const { html, text } = renderDraftEmail(safe, META);
    expect(html).toContain("example.vercel.app");
    expect(html).toMatch(/generated by a visitor/i);
    expect(text).toMatch(/generated by a visitor/i);
  });

  it("produces a plain-text alternative alongside the HTML", () => {
    const { text } = renderDraftEmail(sanitizeRun(validRun())!, META);
    expect(text).toContain("INVESTMENT");
    expect(text).toContain("TOTAL:");
    expect(text).not.toContain("<");
  });
});

describe("checkRateLimit", () => {
  beforeEach(() => resetRateLimits());

  it("allows up to the limit, then blocks", () => {
    const opts = { limit: 3, windowMs: 60_000, now: 1_000 };
    expect(checkRateLimit("ip:1.2.3.4", opts).ok).toBe(true);
    expect(checkRateLimit("ip:1.2.3.4", opts).ok).toBe(true);
    expect(checkRateLimit("ip:1.2.3.4", opts).ok).toBe(true);

    const blocked = checkRateLimit("ip:1.2.3.4", opts);
    expect(blocked.ok).toBe(false);
    expect(blocked.retryAfter).toBeGreaterThan(0);
  });

  it("keys are independent — one sender can't exhaust another's budget", () => {
    const opts = { limit: 1, windowMs: 60_000, now: 1_000 };
    expect(checkRateLimit("ip:1.1.1.1", opts).ok).toBe(true);
    expect(checkRateLimit("ip:1.1.1.1", opts).ok).toBe(false);
    expect(checkRateLimit("ip:2.2.2.2", opts).ok).toBe(true);
  });

  it("frees up once the window slides past", () => {
    const opts = { limit: 1, windowMs: 60_000 };
    expect(checkRateLimit("ip:9.9.9.9", { ...opts, now: 0 }).ok).toBe(true);
    expect(checkRateLimit("ip:9.9.9.9", { ...opts, now: 30_000 }).ok).toBe(false);
    expect(checkRateLimit("ip:9.9.9.9", { ...opts, now: 61_000 }).ok).toBe(true);
  });
});
